const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../assets/web/app.js'),'utf8').replace(/\nboot\(\);\s*$/,'\n');
const ctx={window:{addEventListener(){}},document:{querySelector(){return {}},addEventListener(){}},navigator:{onLine:true},location:{hash:''},URLSearchParams,setTimeout,clearTimeout,console};
vm.createContext(ctx);vm.runInContext(source,ctx);let passed=0;
const run=code=>vm.runInContext(code,ctx),check=fn=>{fn();passed++};
check(()=>assert.equal(run('money(12.3)'), '$12.30'));
check(()=>assert.equal(run('money(12.3,"USD")'), '$12.30'));
check(()=>assert.equal(run('money(12.3,"CNY")'), '¥12.30'));
check(()=>assert.equal(run('money(12.3,"rmb")'), '¥12.30'));
check(()=>assert.equal(run('money(-12.3,"CNY")'), '−¥12.30'));
check(()=>assert.equal(run('money(0,"USD")'), '$0.00'));
check(()=>assert.equal(run('money(null,"USD")'), ''));
check(()=>assert.equal(run('money(12.3,"EUR")'), '€12.30'));
check(()=>assert.equal(run('money(12.3,"GBP")'), '£12.30'));
check(()=>assert.equal(run('money(12.3,"XYZ")'), 'XYZ 12.30'));
run('state.data={currency:"CNY",account:{balance:-10,pending_charges:3.75},invoices:[],invoices_known:true}');
check(()=>assert.equal(run('money(10)'), '¥10.00'));
check(()=>assert.equal(run('accountBalance(-10)'), '¥10.00'));
check(()=>assert.doesNotMatch(run('billingView()'), /month-tag|USD|\$/));
run('state.data.currency="USD"');
check(()=>assert.doesNotMatch(run('billingView()'), /month-tag|USD|¥/));
check(()=>assert.match(run('billingView()'), /\$3\.75/));
check(()=>assert.match(run('billingView()'), /\$10\.00/));
console.log(`Currency symbols: ${passed}/${passed} checks passed`);
